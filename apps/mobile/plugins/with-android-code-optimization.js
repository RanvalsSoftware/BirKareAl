const { withAppBuildGradle, withGradleProperties } = require('expo/config-plugins');

const optimizationProperties = {
  'android.enableMinifyInReleaseBuilds': 'true',
  'android.enableShrinkResourcesInReleaseBuilds': 'true',
  'android.r8.optimizedResourceShrinking': 'true',
};

const revenueCatAmazonExclusion = `// @generated by with-android-code-optimization
// BirKare ships through Google Play only. RevenueCat's optional Amazon module
// contributes a global -dontoptimize consumer rule, which prevents R8 from
// optimizing the whole app and tanks Play's DEX optimization score.
configurations.configureEach {
    exclude group: "com.revenuecat.purchases", module: "purchases-store-amazon"
}`;

function upsertGradleProperty(properties, key, value) {
  const filtered = properties.filter(
    (property) => property.type !== 'property' || property.key !== key,
  );
  filtered.push({ type: 'property', key, value });
  return filtered;
}

function useOptimizedDefaultRules(contents) {
  const legacyRules = /getDefaultProguardFile\((['"])proguard-android\.txt\1\)/g;
  if (!legacyRules.test(contents)) {
    if (contents.includes('proguard-android-optimize.txt')) return contents;
    throw new Error('BirKare Android release ProGuard configuration was not found.');
  }
  return contents.replace(legacyRules, 'getDefaultProguardFile("proguard-android-optimize.txt")');
}

function excludeUnusedRevenueCatAmazonStore(contents) {
  if (contents.includes(revenueCatAmazonExclusion)) return contents;

  const androidBlock = /(^|\n)android\s*\{/;
  if (!androidBlock.test(contents)) {
    throw new Error('BirKare Android application Gradle block was not found.');
  }

  return contents.replace(androidBlock, `$1${revenueCatAmazonExclusion}\n\nandroid {`);
}

module.exports = function withAndroidCodeOptimization(config) {
  config = withGradleProperties(config, (mod) => {
    for (const [key, value] of Object.entries(optimizationProperties)) {
      mod.modResults = upsertGradleProperty(mod.modResults, key, value);
    }
    return mod;
  });

  return withAppBuildGradle(config, (mod) => {
    if (mod.modResults.language !== 'groovy')
      throw new Error('BirKare Android optimization requires Groovy build.gradle.');
    mod.modResults.contents = excludeUnusedRevenueCatAmazonStore(
      useOptimizedDefaultRules(mod.modResults.contents),
    );
    return mod;
  });
};

module.exports.optimizationProperties = optimizationProperties;
module.exports.upsertGradleProperty = upsertGradleProperty;
module.exports.useOptimizedDefaultRules = useOptimizedDefaultRules;
module.exports.excludeUnusedRevenueCatAmazonStore = excludeUnusedRevenueCatAmazonStore;
